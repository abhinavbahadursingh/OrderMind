import type { CSSProperties, ReactNode } from 'react'
import { Icon } from './Icons'

/* ---- chat thread ------------------------------------------------------- */

export type ChatMessage = {
  from: 'in' | 'out'
  text: string
  meta?: string
  marks?: string[]
}

function withMarks(text: string, marks: string[] | undefined) {
  if (!marks || marks.length === 0) return text
  const pattern = new RegExp(`(${marks.map((m) => m.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`, 'g')
  const parts = text.split(pattern)
  return parts.map((part, i) =>
    marks.includes(part) ? (
      <mark key={i}>{part}</mark>
    ) : (
      <span key={i}>{part}</span>
    ),
  )
}

export function ChatThread({ messages }: { messages: ChatMessage[] }) {
  return (
    <div className="thread">
      {messages.map((m, i) => (
        <div
          key={i}
          className={`bubble bubble--${m.from}`}
          style={{ '--bi': i } as CSSProperties}
        >
          <span>{withMarks(m.text, m.marks)}</span>
          {m.meta ? <span className="bubble__meta">{m.meta}</span> : null}
        </div>
      ))}
    </div>
  )
}

/* ---- structured order -------------------------------------------------- */

export type OrderLine = {
  name: string
  qty: number
  price: string
  meta: string[]
  updated?: boolean
}

export function OrderCard({
  id,
  status,
  statusTone = 'draft',
  lines,
  total,
  action,
}: {
  id: string
  status: string
  statusTone?: 'draft' | 'review' | 'paid'
  lines: OrderLine[]
  total: string
  action?: ReactNode
}) {
  return (
    <div className="order-card">
      <div className="order-card__head">
        <span className="order-card__id">{id}</span>
        <span className={`status status--${statusTone}`}>{status}</span>
      </div>
      <div className="order-card__rows">
        {lines.map((line, i) => (
          <div key={i} className={`order-row${line.updated ? ' is-updated' : ''}`}>
            <div className="order-row__main">
              <div className="order-row__name">
                {line.name} <span className="muted">× {line.qty}</span>
              </div>
              <div className="order-row__meta">
                {line.meta.map((m) => (
                  <span key={m} className="chip">
                    {m}
                  </span>
                ))}
              </div>
            </div>
            <div className="order-row__price">{line.price}</div>
          </div>
        ))}
      </div>
      <div className="order-card__foot">
        <span>Total payable</span>
        <span className="order-card__total">{total}</span>
        {action}
      </div>
    </div>
  )
}

