/* ---- JSON state --------------------------------------------------------- */

function colorize(text: string) {
  const parts = text.split(/("(?:[^"\\]|\\.)*")/g)
  return parts.map((part, i) => {
    if (i % 2 === 0) return <span key={i}>{part}</span>
    const isKey = /^\s*:/.test(parts[i + 1] ?? '')
    return (
      <span key={i} className={isKey ? 'k' : 's'}>
        {part}
      </span>
    )
  })
}

export function StatePanel({
  lines,
}: {
  lines: (string | { text: string; changed?: boolean })[]
}) {
  const normalized = lines.map((l) => (typeof l === 'string' ? { text: l } : l))
  return (
    <div className="state-panel">
      <div className="state-panel__bar">
        <Icon name="code" size={14} />
        <span>order_state.json</span>
      </div>
      <div className="state-panel__body">
        {normalized.map((l, i) => (
          <div key={i} className={`state-line${l.changed ? ' is-changed' : ''}`}>
            {colorize(l.text)}
          </div>
        ))}
      </div>
    </div>
  )
}
